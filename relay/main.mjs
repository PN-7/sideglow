import { loadConfig } from './config.mjs';
import { EventStore } from './store.mjs';
import { NonceLedger } from './nonce.mjs';
import { DiscordRest, DiscordBridge } from './discord.mjs';
import { createRelayServer } from './server.mjs';

async function main() {
  if (Number(process.versions.node.split('.')[0]) < 22 || typeof WebSocket === 'undefined') {
    throw new Error('Node.js 22 or newer, with built-in WebSocket support, is required');
  }
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) {
    console.log('Usage: node relay/main.mjs --config relay/config.json\nGenerate a user key: node relay/keygen.mjs');
    return;
  }
  if (args.length !== 2 || args[0] !== '--config') throw new Error('Usage: node relay/main.mjs --config relay/config.json');
  const config = await loadConfig(args[1]);
  const ledger = new NonceLedger(config.stateDirectory);
  await ledger.open();
  const store = new EventStore();
  const rest = new DiscordRest(config);
  // This catches a webhook accidentally pointing at a different channel before any user can send.
  await rest.verifyWebhook();
  const bridge = new DiscordBridge(config, store, rest);
  const server = await createRelayServer({
    config, store, ledger,
    send: async (displayName, content) => {
      const message = await rest.send(displayName, content);
      bridge.ingestWebhook(message);
      return { id: message.id };
    },
  });
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(config.listen.port, config.listen.host, resolve);
  });
  bridge.start();
  const address = config.listen.host.includes(':') ? `[${config.listen.host}]` : config.listen.host;
  console.log(`Sideglow relay listening at ${config.listen.tls ? 'https' : 'http'}://${address}:${config.listen.port}`);
  console.log('Waiting for Discord history synchronization. No secrets or message text are logged.');
  let stopping = false;
  const shutdown = () => {
    if (stopping) return;
    stopping = true;
    bridge.stop();
    server.close(() => { process.exitCode = 0; });
    server.closeIdleConnections();
    setTimeout(() => server.closeAllConnections(), 3000).unref();
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

main().catch((error) => {
  // Errors generated by these modules contain no credentials, request body, or webhook URL.
  console.error(`Sideglow relay could not start: ${error.message}`);
  process.exitCode = 1;
});
